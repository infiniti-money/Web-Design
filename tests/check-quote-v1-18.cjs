const {chromium}=require("playwright");
const fs=require("node:fs");
const path=require("node:path");
const assert=require("node:assert/strict");
(async()=>{
 const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:900},locale:"vi-VN"});
  const errors=[],external=[];
  await page.addInitScript(()=>{window.print=()=>{window.__printInvoked=true}});
  page.on("pageerror",e=>errors.push(e.message));
  page.on("request",r=>{if(!r.url().startsWith("http://127.0.0.1:8765/"))external.push(r.url())});
  await page.goto("http://127.0.0.1:8765/preview-v1-17/interactive-demo.html",{waitUntil:"networkidle"});
  const quote=page.locator("#quotes .item").filter({hasText:"Thiết kế nội thất căn hộ 90 m²"});
  await quote.getByRole("button",{name:"Chi tiết hạng mục"}).click();
  await page.locator("#tan-quote-editor").waitFor({state:"visible"});
  const rows=page.locator(".tan-detail-row");
  const row0=rows.first();
  await row0.locator("input").nth(1).fill("Tấm ốp gỗ công nghiệp");
  await row0.locator("input").nth(2).fill("m²");
  await row0.locator("input").nth(3).fill("2.5");
  await row0.locator("input").nth(4).fill("175000");
  await page.getByRole("button",{name:"+ Thêm hạng mục"}).click();
  const row1=rows.nth(1);
  await row1.locator("input").nth(0).fill("Thi công");
  await row1.locator("input").nth(1).fill("Lắp đặt và hoàn thiện");
  await row1.locator("input").nth(2).fill("công");
  await row1.locator("input").nth(3).fill("3");
  await row1.locator("input").nth(4).fill("320000");
  await page.locator(".tan-cost-summary input").fill("100000");
  await page.locator(".tan-cost-summary select").selectOption("10");
  await page.locator(".tan-grand-total").getByText("1.427.250").waitFor();
  await page.screenshot({path:"preview-v1-17/v1-18-editor-desktop.png",fullPage:true,animations:"disabled"});
  await page.getByRole("button",{name:"Lưu phiên bản báo giá"}).click();
  await page.locator("#tan-quote-editor").waitFor({state:"detached"});
  await quote.getByRole("button",{name:"In A4 / PDF"}).click();
  assert.equal(await page.evaluate(()=>window.__printInvoked),true,"Print action should invoke browser print");
  const printable=page.locator("#tan-print-sheet");
  assert.match(await printable.innerText(),/Tấm ốp gỗ công nghiệp/);
  assert.match(await printable.innerText(),/1\.427\.250/);
  await page.emulateMedia({media:"print"});
  assert.equal(await page.locator("body > div").first().isVisible(),false,"Preview banner must never print");
  assert.equal(await printable.isVisible(),true,"Only the print document should be visible");
  // Keep print media active while Playwright generates the A4 PDF.
  const output=path.join(process.cwd(),"preview-v1-17","v1-18-quote-a4.pdf");
  const pdf=await page.pdf({path:output,format:"A4",printBackground:true});
  assert.ok(pdf.length>5000&&pdf.subarray(0,5).toString()==="%PDF-","PDF must be a real PDF");
  assert.deepEqual(errors,[],"JavaScript errors in detailed quote workflow");
  assert.deepEqual(external,[],"Offline demo must not access production services");
  fs.writeFileSync("preview-v1-17/v1-18-quote-report.json",JSON.stringify({passed:true,total:1427250,items:2,pdfBytes:pdf.length,externalRequests:external.length},null,2));
  console.log("V1.18 PASS: item editing, saved snapshot, A4 PDF, zero external requests");
  // Chromium phone-sized viewport; validates responsive editing and A4 print.
  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true,locale:"vi-VN"});
  const phoneErrors=[],phoneExternal=[];
  await mobile.addInitScript(()=>{window.print=()=>{window.__phonePrintCalled=true}});
  mobile.on("pageerror",e=>phoneErrors.push(e.message));
  mobile.on("request",r=>{if(!r.url().startsWith("http://127.0.0.1:8765/"))phoneExternal.push(r.url())});
  await mobile.goto("http://127.0.0.1:8765/preview-v1-17/interactive-demo.html",{waitUntil:"networkidle"});
  const phoneQuote=mobile.locator("#quotes .item").filter({hasText:"Thiết kế nội thất căn hộ 90 m²"});
  await phoneQuote.getByRole("button",{name:"Chi tiết hạng mục"}).click();
  await mobile.locator("#tan-quote-editor").waitFor({state:"visible"});
  const mobileOverflow=await mobile.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+3);
  assert.equal(mobileOverflow,false,"Mobile editor must not overflow screen width");
  await mobile.screenshot({path:"preview-v1-17/v1-18-editor-mobile-390.png",fullPage:true,animations:"disabled"});
  await mobile.locator("#tan-quote-editor").getByRole("button",{name:"Đóng"}).click();
  await phoneQuote.getByRole("button",{name:"In A4 / PDF"}).click();
  assert.equal(await mobile.evaluate(()=>window.__phonePrintCalled),true,"Mobile print action must invoke browser print");
  await mobile.emulateMedia({media:"print"});
  assert.equal(await mobile.locator("#tan-print-sheet").isVisible(),true);
  const mobilePDF=await mobile.pdf({path:"preview-v1-17/v1-18-quote-mobile-A4.pdf",format:"A4",printBackground:true});
  assert.ok(mobilePDF.length>5000&&mobilePDF.subarray(0,5).toString()==="%PDF-");
  assert.deepEqual(phoneErrors,[],"No mobile JavaScript errors");
  assert.deepEqual(phoneExternal,[],"Offline preview must not connect externally");
  console.log("V1.18 PHONE PASS: 390px editor, no overflow, A4 PDF");
  await mobile.close();
  await page.close();
 }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1});
