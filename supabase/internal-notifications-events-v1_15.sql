-- v1.15 server-generated notifications for new and reassigned tasks.
create or replace function public.notify_task_assignment()
returns trigger language plpgsql security definer set search_path=''
as $$
declare event_kind text; event_id text;
begin
 if new.assignee_user_id is null then return new; end if;
 if tg_op='INSERT' then event_kind:='new_task';
 elsif new.assignee_user_id is distinct from old.assignee_user_id then event_kind:='reassigned';
 else return new; end if;
 if not exists(select 1 from public.staff_profiles s where s.user_id=new.assignee_user_id and s.active) then return new; end if;
 event_id:=new.id::text||':'||event_kind||':'||new.assignee_user_id::text||':'||new.updated_at::text;
 insert into public.staff_notifications(recipient_id,task_id,event_key,kind,title,body)
 values(new.assignee_user_id,new.id,event_id,event_kind,
 case when event_kind='new_task' then 'Công việc mới được giao' else 'Bạn được giao phụ trách công việc' end,
 left(new.title,600)) on conflict(recipient_id,event_key) do nothing;
 return new;
end;$$;
drop trigger if exists task_assignment_notification on public.inquiry_care_tasks;
create trigger task_assignment_notification after insert or update of assignee_user_id on public.inquiry_care_tasks
for each row execute function public.notify_task_assignment();
-- Due reminders can be generated by scheduled trusted calls, not when pages are viewed.
create or replace function public.generate_task_due_notifications()
returns integer language plpgsql security definer set search_path=''
as $$
declare actor_role text; inserted_rows integer;
begin
 select s.role into actor_role from public.staff_profiles s where s.user_id=auth.uid() and s.active
 and s.role='admin' and auth.jwt()->'app_metadata'->>'role'=s.role;
 if actor_role is null then raise exception 'ADMIN_REQUIRED' using errcode='42501';end if;
 insert into public.staff_notifications(recipient_id,task_id,event_key,kind,title,body)
 select t.assignee_user_id,t.id,t.id::text||':due:'||case when t.due_at<now() then 'overdue:'||to_char(t.due_at,'YYYYMMDDHH24MI') else 'soon:'||to_char(t.due_at,'YYYYMMDDHH24MI') end,
 case when t.due_at<now() then 'overdue' else 'due_soon' end,
 case when t.due_at<now() then 'Công việc quá hạn' else 'Công việc sắp đến hạn' end,
 left(t.title,600)
 from public.inquiry_care_tasks t join public.staff_profiles s on s.user_id=t.assignee_user_id and s.active
 where t.due_at is not null and t.completed_at is null
 and t.status not in ('completed','cancelled')
 and t.due_at < now()+interval '24 hours'
 on conflict(recipient_id,event_key) do nothing;
 get diagnostics inserted_rows=row_count;
 return inserted_rows;
end;$$;
revoke all on function public.generate_task_due_notifications() from public,anon;
grant execute on function public.generate_task_due_notifications() to authenticated;
